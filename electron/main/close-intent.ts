/**
 * Кто попросил закрыть окно.
 *
 * Окно у программы своё, без рамки Windows: крестик нарисован в интерфейсе и
 * приходит оттуда вызовом. А «Завершить задачу» в панели задач приходит как
 * WM_CLOSE от самой системы — мимо интерфейса, и отличить её больше не по чему.
 *
 * Различать их обязательно. Программа на всякую просьбу закрыться пряталась в
 * трей — так работает настройка «свернуть в трей», и для крестика это верно.
 * Но «Завершить задачу» после этого считало задачу исполненной: окна-то не
 * стало. Программа оставалась жить в трее, а с ней и TgWsProxy. Дальше можно
 * было сколько угодно совершенствовать добивание процессов: умирать должно
 * было нечто, что и не думало умирать.
 *
 * Признак живёт две секунды: от щелчка по крестику до самого закрытия окна
 * проходят единицы миллисекунд, но медленный компьютер под нагрузкой не должен
 * из-за этого лишать человека привычного поведения.
 */

/** Когда последний раз закрывать окно просил сам интерфейс. */
let askedAt = 0

const FRESH_MS = 2000

/** Помечает: закрыть окно просит нарисованный в интерфейсе крестик. */
export function markUiClose(): void {
  askedAt = Date.now()
}

/** Закрывает ли окно сам интерфейс, а не система. */
export function isUiClose(): boolean {
  return askedAt > 0 && Date.now() - askedAt <= FRESH_MS
}

/** Сбрасывает признак: разобранная просьба не должна сработать дважды. */
export function resetUiClose(): void {
  askedAt = 0
}
