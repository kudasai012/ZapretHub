/**
 * Как часто спрашивать состояние компонентов.
 *
 * Раньше программа опрашивала их раз в 0,7 с при любых обстоятельствах и
 * рассылала состояние всем окнам — даже свёрнутым в трей, где перерисовывать
 * нечего. Теперь частота зависит от того, видно ли окно: на экране состояние
 * нужно сразу, из трея — достаточно значка, который обновляется втрое реже.
 *
 * Функция одна и намеренно простая: по ней стенд проверяет сам выбор, не
 * подстраивая часы и не дожидаясь настоящего прохода опроса.
 */

/** Как часто спрашивать состояние, когда окно на экране. */
export const POLL_VISIBLE_MS = 700
/** Как часто спрашивать состояние, когда программы не видно. */
export const POLL_HIDDEN_MS = 3000

/**
 * Сколько ждать до следующего опроса.
 *
 * @param visible окно на экране: человек смотрит на него и ждёт свежих цифр.
 */
export function pollPeriodMs(visible: boolean): number {
  return visible ? POLL_VISIBLE_MS : POLL_HIDDEN_MS
}
